#!/usr/bin/env bash
# End-to-end walkthrough against a running API (`make api`) using the dev mail sink and the
# synthetic fixtures (`make fixtures`). Prints each request and a trimmed response.
# Requires: curl, jq. Usage: BASE=http://localhost:8080 scripts/demo.sh
set -euo pipefail
BASE=${BASE:-http://localhost:8080}
EMAIL=${EMAIL:-demo.$(date +%s)@example.com}
PASS='Str0ng-Passw0rd!'
TOKEN=""

call() { # method path [json]
  local m=$1 p=$2 d=${3:-}
  echo "--> $m $p" >&2
  local args=(-sS -X "$m" "$BASE$p" -H 'Content-Type: application/json')
  [[ -n $TOKEN ]] && args+=(-H "Authorization: Bearer $TOKEN")
  [[ -n $d ]] && args+=(-d "$d")
  curl "${args[@]}"
}
show() { jq -c "$1" | cut -c1-400; echo; }

echo "== anonymous access is refused"
call GET /v1/feed | show '{status, code}'

echo "== register → code from the dev mailbox → verify"
call POST /v1/auth/register "{\"first_name\":\"Demo\",\"last_name\":\"User\",\"email\":\"$EMAIL\",\"phone\":\"069123456\",\"password\":\"$PASS\",\"accept_terms\":true,\"accept_privacy\":true,\"locale\":\"ro\"}" | show .
CODE=""
for _ in $(seq 1 20); do # mail is delivered by the worker (`make worker`)
  CODE=$(call GET "/v1/dev/mailbox?to=$EMAIL" 2>/dev/null | jq -r '.items[0].body // empty' | grep -oE '\b[0-9]{6}\b' | head -1 || true)
  [[ -n $CODE ]] && break
  sleep 1
done
[[ -n $CODE ]] || { echo "no verification email yet: is the worker running?" >&2; exit 1; }
VER=$(call POST /v1/auth/verify-email "{\"email\":\"$EMAIL\",\"code\":\"$CODE\"}")
echo "$VER" | show '{token_type, expires_in, user: {email: .user.email, status: .user.status}}'
TOKEN=$(echo "$VER" | jq -r .access_token)
REFRESH=$(echo "$VER" | jq -r .refresh_token)

echo "== onboarding: categories from the dynamic taxonomy"
CATS=$(call GET "/v1/categories/tree?lang=ro")
echo "$CATS" | show '[.items[] | {slug, ro: .names.ro, ru: .names.ru}] | .[0:6]'
ENERGY=$(echo "$CATS" | jq -r '.. | objects | select(.slug?=="energy") | .id' | head -1)
call PUT /v1/users/me/categories "{\"category_ids\":[\"$ENERGY\"]}" | show '[.items[] | {interest_type, mode}]'

echo "== feed, event detail with citations, timeline"
FEED=$(call GET "/v1/feed?limit=5")
echo "$FEED" | show '[.items[] | {title: .event.title, reasons}]'
EVENT=$(echo "$FEED" | jq -r '.items[0].event.id')
call GET "/v1/events/$EVENT?lang=ro" | show '{title, article_count, source_count, citation_coverage, summary: (.summary.short)}'
call GET "/v1/events/$EVENT/sources" | show '[.items[] | {publisher, url, relation}]'
call GET "/v1/events/$EVENT/timeline" | show '[.items[] | {kind, severity, occurred_at}]'

echo "== search (hybrid; degraded components are reported, never hidden)"
call GET "/v1/search?q=tarif%20energie" | show '{degraded, hits: [.items[] | {type, title}][0:5]}'

echo "== fact-checks: unverified is not false; definitive labels require review"
call GET "/v1/fact-checks?limit=5" | show '[.items[] | {claim, verdict, review_status}]'

echo "== grounded chat"
S=$(call POST /v1/chat/sessions "{\"scope_type\":\"event\",\"scope_id\":\"$EVENT\",\"language\":\"en\"}" | jq -r .id)
call POST "/v1/chat/sessions/$S/messages" '{"content":"Why is this important for a Moldova business?"}' | show '{content, abstained, uncertainty, citations: [.citations[] | {ref, type, title}]}'

echo "== briefing (generated by the worker or \`newsctl drain\`)"
B=$(call POST /v1/briefings '{"duration_minutes":5,"language":"ro"}')
echo "$B" | show '{id, status}'

echo "== notification schedule (Europe/Chisinau, DST-aware)"
call PUT /v1/notifications/schedules '{"kind":"daily","local_times":["08:00"],"timezone":"Europe/Chisinau","quiet_start":"22:00","quiet_end":"07:00"}' | show '{name, local_times, timezone, next_run_at}'

echo "== refresh rotation"
TOKEN="" call POST /v1/auth/refresh "{\"refresh_token\":\"$REFRESH\"}" | show '{token_type, expires_in}'
echo "== reusing the old refresh token is detected (family revoked)"
TOKEN="" call POST /v1/auth/refresh "{\"refresh_token\":\"$REFRESH\"}" | show '{status, code}'
